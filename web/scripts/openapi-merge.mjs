// Merges api/openapi/_common.yaml + every module fragment into
// api/openapi.gen.yaml (gitignored), failing on duplicate operations or schema
// names, then generates src/api/schema.gen.ts with openapi-typescript.
// The Go side never depends on these outputs (apitest loads fragments itself).
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import YAML from 'yaml';
import openapiTS, { astToString } from 'openapi-typescript';
import { repoDir, webDir, withLock, writeAtomic } from './lib.mjs';

const specDir = path.join(repoDir, 'api', 'openapi');
const merged = path.join(repoDir, 'api', 'openapi.gen.yaml');
const schemaTS = path.join(webDir, 'src', 'api', 'schema.gen.ts');

function rewriteRefs(node) {
  if (Array.isArray(node)) return node.map(rewriteRefs);
  if (node && typeof node === 'object') {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      out[k] = k === '$ref' && typeof v === 'string' ? v.replace(/^_common\.yaml#/, '#') : rewriteRefs(v);
    }
    return out;
  }
  return node;
}

export function mergeSpecs() {
  const common = YAML.parse(fs.readFileSync(path.join(specDir, '_common.yaml'), 'utf8'));
  const doc = {
    openapi: common.openapi,
    info: { title: 'pcc internal API (generated, unpublished)', version: '0' },
    paths: {},
    components: { schemas: { ...(common.components?.schemas ?? {}) }, responses: { ...(common.components?.responses ?? {}) } },
  };
  const files = fs.readdirSync(specDir).filter((f) => f.endsWith('.yaml') && !f.startsWith('_')).sort();
  for (const f of files) {
    const frag = rewriteRefs(YAML.parse(fs.readFileSync(path.join(specDir, f), 'utf8')) ?? {});
    for (const [p, ops] of Object.entries(frag.paths ?? {})) {
      const target = (doc.paths[p] ??= {});
      for (const [method, op] of Object.entries(ops ?? {})) {
        if (target[method]) throw new Error(`${f}: duplicate operation ${method.toUpperCase()} ${p}`);
        target[method] = op;
      }
    }
    for (const kind of ['schemas', 'responses']) {
      for (const [name, s] of Object.entries(frag.components?.[kind] ?? {})) {
        if (doc.components[kind][name]) throw new Error(`${f}: duplicate ${kind} ${name}`);
        doc.components[kind][name] = s;
      }
    }
  }
  return doc;
}

export async function generateAPI() {
  await withLock(async () => {
    const doc = mergeSpecs();
    writeAtomic(merged, YAML.stringify(doc));
    const ast = await openapiTS(pathToFileURL(merged));
    const header = '// GENERATED by web/scripts/openapi-merge.mjs from api/openapi/*.yaml. Do not edit.\n';
    writeAtomic(schemaTS, header + astToString(ast));
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateAPI();
}
